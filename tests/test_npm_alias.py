@pytest.mark.parametrize("descriptor, expected", [
    ("string-width-cjs@npm:string-width@^4.2.0", ("string-width-cjs", "string-width", "^4.2.0")),
    ("string-width-cjs@npm:string-width@4.2.3", ("string-width-cjs", "string-width", "4.2.3")),
    ("@scope/x@npm:@scope/y@1.2.3", ("@scope/x", "@scope/y", "1.2.3")),
    ("x@npm:@scope/y", ("x", "@scope/y", "")),
    ("x@npm:y", ("x", "y", "")),
])
def test_parse_npm_alias_reads_the_real_name(descriptor, expected):
    assert parse_npm_alias(descriptor) == expected


@pytest.mark.parametrize("descriptor", [
    "x@npm:", "x@npm:@scope", "x@npm:@scope@1.0.0", "x@npm:bad name@1",
    "x@npm:y@", "bad alias@npm:y@1", "x@npm:@a/b/c@1",
])
def test_parse_npm_alias_marks_a_malformed_alias(descriptor):
    alias = parse_npm_alias(descriptor)
    assert alias is not None and alias[1] is None


@pytest.mark.parametrize("descriptor", ["lodash@^4.17.21", "@types/node@22.5.0", "npm@10.0.0"])
def test_parse_npm_alias_ignores_a_plain_descriptor(descriptor):
    assert parse_npm_alias(descriptor) is None


def test_split_npm_target():
    assert split_npm_target("string-width@4.2.3") == ("string-width", "4.2.3")
    assert split_npm_target("@scope/y@1.2.3") == ("@scope/y", "1.2.3")
    assert split_npm_target("@scope") == (None, None)


# ---------------------------------------------------------------- parsers


def test_yarn_v1_alias_keys_resolve_to_the_real_package():
    outcome = parse("yarn.lock", YARN_V1, "yarn.lock")
    assert keys(outcome) == {
        (NPM, "string-width", "4.2.3"),
        (NPM, "strip-ansi", "6.0.1"),
        (NPM, "wrap-ansi", "7.0.0"),
        (NPM, "@scope/y", "1.2.3"),
        (NPM, "fresh-pkg", "2.0.0"),
    }
    assert outcome.skips == []
    assert outcome.errors == []


def test_yarn_v1_malformed_alias_is_kept_as_a_dep_not_skipped():
    outcome = parse("yarn.lock", MALFORMED_YARN_V1, "yarn.lock")
    names = {dep.name for dep in outcome.deps}
    assert "left-pad" in names
    # The malformed key is second in its block; it must still be read.
    assert "broken@npm:bad name@^1.0.0" in names
    assert "empty@npm:" in names
    assert "half-scope@npm:@scope@1.0.0" in names
    assert outcome.skips == []


def test_package_lock_v1_alias_resolves_to_the_real_package():
    lock = {"lockfileVersion": 1, "dependencies": {
        "string-width-cjs": {"version": "npm:string-width@4.2.3"},
        "@scope/x": {"version": "npm:@scope/y@1.2.3"},
        "broken": {"version": "npm:bad name@1.0.0"},
    }}
    outcome = parse("package-lock.json", json.dumps(lock), "package-lock.json")
    assert (NPM, "string-width", "4.2.3") in keys(outcome)
    assert (NPM, "@scope/y", "1.2.3") in keys(outcome)
    assert any(dep.detail == "malformed npm alias" for dep in outcome.deps)
    assert outcome.skips == []


def test_package_lock_v3_alias_uses_the_name_field():
    lock = {"lockfileVersion": 3, "packages": {
        "": {"name": "root"},
        "node_modules/string-width-cjs": {
            "name": "string-width", "version": "4.2.3",
            "resolved": "https://registry.npmjs.org/string-width/-/string-width-4.2.3.tgz",
        },
    }}
    outcome = parse("package-lock.json", json.dumps(lock), "package-lock.json")
    assert keys(outcome) == {(NPM, "string-width", "4.2.3")}


def test_pnpm_alias_key_resolves_to_the_real_package():
    text = (
        "lockfileVersion: '9.0'\n\npackages:\n\n"
        "  string-width@4.2.3:\n    resolution: {integrity: sha512-x}\n\n"
        "  string-width-cjs@npm:string-width@4.2.3:\n    resolution: {integrity: sha512-x}\n\n"
        "  '@scope/x@npm:@scope/y@1.2.3':\n    resolution: {integrity: sha512-x}\n\n"
        "  broken@npm:@scope@1.0.0:\n    resolution: {integrity: sha512-x}\n"
    )
    outcome = parse("pnpm-lock.yaml", text, "pnpm-lock.yaml")
    assert (NPM, "string-width", "4.2.3") in keys(outcome)
    assert (NPM, "@scope/y", "1.2.3") in keys(outcome)
    assert any(dep.detail == "malformed npm alias" for dep in outcome.deps)
    assert outcome.skips == []


# ---------------------------------------------------------------- grading


def test_alias_of_an_old_real_package_passes():
    outcome = parse("yarn.lock", YARN_V1, "yarn.lock")
    deps = [d for d in outcome.deps if d.name != "fresh-pkg"]
    results = client(alias_transport()).evaluate(deps, MIN_AGE, now=NOW)
    assert {r.dep.name: r.status for r in results} == {
        "string-width": "PASS", "strip-ansi": "PASS", "wrap-ansi": "PASS", "@scope/y": "PASS",
    }


def test_alias_of_a_young_real_version_fails():
    outcome = parse("yarn.lock", YARN_V1, "yarn.lock")
    results = client(alias_transport()).evaluate(outcome.deps, MIN_AGE, now=NOW)
    status = {r.dep.name: r.status for r in results}
    assert status["fresh-pkg"] == "FAIL"
    assert all(r.status in ("PASS", "FAIL") for r in results)


def test_malformed_alias_is_unknown_without_a_network_call():
    outcome = parse("yarn.lock", MALFORMED_YARN_V1, "yarn.lock")
    malformed = [d for d in outcome.deps if d.name != "left-pad"]
    results = client(ExplodingTransport()).evaluate(malformed, MIN_AGE, now=NOW)
    assert len(results) == 3
    assert all(r.status == "UNKNOWN" and r.failed for r in results)
    assert all("not a valid npm package name" in r.message for r in results)


def test_audit_exit_codes_for_alias_lockfiles(monkeypatch, capsys, tmp_path):
    # cli grades against the real clock, so the canned dates follow it.
    transport = alias_transport(now=datetime.now(timezone.utc))
    real_client = RegistryClient

    def make_client(cache=None, workers=12, **_):
        return real_client(cache=Cache(enabled=False), transport=transport, workers=1)

    monkeypatch.setattr(cli, "RegistryClient", make_client)
    old_only = tmp_path / "old" / "yarn.lock"
    old_only.parent.mkdir()
    old_only.write_text(YARN_V1.split('"fresh-alias')[0], encoding="utf-8")
    assert cli.main(["audit", "--lock", str(old_only)]) == 0

    young = tmp_path / "young" / "yarn.lock"
    young.parent.mkdir()
    young.write_text(YARN_V1, encoding="utf-8")
    assert cli.main(["audit", "--lock", str(young)]) == 1
    assert "fresh-pkg" in capsys.readouterr().out

    broken = tmp_path / "broken" / "yarn.lock"
    broken.parent.mkdir()
    broken.write_text(MALFORMED_YARN_V1, encoding="utf-8")
    assert cli.main(["audit", "--lock", str(broken)]) == 1
