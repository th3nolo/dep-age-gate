"""npm aliases (`<alias>@npm:<real>@<range>`) are checked as the REAL package.

yarn v1 writes the alias as the lockfile key; package-lock v1 writes it as
`"version": "npm:<real>@<ver>"`; package-lock v2/v3 records the real name in
`"name"`; pnpm keys `packages:` by the real name. In every form the publish
date of <real>@<version> decides PASS/FAIL. An alias that cannot be read is
UNKNOWN (fail closed), never skipped or allowed.

No test here touches the network.
"""

import json
from datetime import datetime, timedelta, timezone

import pytest

from dep_age_gate import cli
from dep_age_gate.cache import Cache
from dep_age_gate.model import NPM, Dep
from dep_age_gate.parsers import parse
from dep_age_gate.parsers._common import parse_npm_alias, split_npm_target
from dep_age_gate.registry import RegistryClient
from test_registry import ExplodingTransport, FakeTransport

NOW = datetime(2026, 10, 19, 12, 0, 0, tzinfo=timezone.utc)
MIN_AGE = 4320 * 60  # 72 h


def iso(moment):
    return moment.isoformat().replace("+00:00", "Z")


def keys(outcome):
    return {dep.key for dep in outcome.deps}


YARN_V1 = '''# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"string-width-cjs@npm:string-width@^4.2.0", "string-width@^4.1.0":
  version "4.2.3"
  resolved "https://registry.npmjs.org/string-width/-/string-width-4.2.3.tgz"
  integrity sha512-x

"strip-ansi-cjs@npm:strip-ansi@^6.0.1":
  version "6.0.1"
  resolved "https://registry.npmjs.org/strip-ansi/-/strip-ansi-6.0.1.tgz"

wrap-ansi-cjs@npm:wrap-ansi@7.0.0:
  version "7.0.0"
  resolved "https://registry.npmjs.org/wrap-ansi/-/wrap-ansi-7.0.0.tgz"

"@scope/x@npm:@scope/y@^1.2.0":
  version "1.2.3"
  resolved "https://registry.npmjs.org/@scope/y/-/y-1.2.3.tgz"

"fresh-alias@npm:fresh-pkg@^2.0.0":
  version "2.0.0"
  resolved "https://registry.npmjs.org/fresh-pkg/-/fresh-pkg-2.0.0.tgz"
'''

MALFORMED_YARN_V1 = '''# yarn lockfile v1


"left-pad@^1.3.0", "broken@npm:bad name@^1.0.0":
  version "1.3.0"
  resolved "https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz"

"empty@npm:":
  version "1.0.0"
  resolved "https://registry.npmjs.org/empty/-/empty-1.0.0.tgz"

"half-scope@npm:@scope@1.0.0":
  version "1.0.0"
  resolved "https://registry.npmjs.org/x/-/x-1.0.0.tgz"
'''


def npm_times(versions):
    return {"time": {"created": "2010-01-01T00:00:00.000Z", **versions}}


def alias_transport(now=NOW):
    old = iso(now - timedelta(days=900))
    return FakeTransport(json_payloads={
        "registry.npmjs.org/string-width": npm_times({"4.2.3": "2021-09-23T15:56:53.420Z"}),
        "registry.npmjs.org/strip-ansi": npm_times({"6.0.1": "2021-09-23T16:05:37.211Z"}),
        "registry.npmjs.org/wrap-ansi": npm_times({"7.0.0": "2020-04-22T12:25:59.129Z"}),
        "registry.npmjs.org/@scope%2Fy": npm_times({"1.2.3": old}),
        # 10 hours old: younger than 72 h.
        "registry.npmjs.org/fresh-pkg": npm_times({"2.0.0": iso(now - timedelta(hours=10))}),
        "registry.npmjs.org/left-pad": npm_times({"1.3.0": old}),
    })


def client(transport):
    return RegistryClient(cache=Cache(enabled=False), transport=transport, workers=1)


